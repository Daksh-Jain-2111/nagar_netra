export function t(key: keyof typeof STRINGS, lang: AppLanguage): string {
  const item = STRINGS[key];
  if (!item) return key;
  return item[lang] || item['mr'] || item['en'] || key;
}

/** t() with {placeholder} substitution, e.g. tf('aiConfidence', lang, { n: 94 }). */
export function tf(key: keyof typeof STRINGS, lang: AppLanguage, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce((text, [k, v]) => text.split(`{${k}}`).join(String(v)), t(key, lang));
}
